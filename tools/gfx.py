#!/usr/bin/env python3
"""Prince of Persia (ZX) graphics <-> PNG.

    python tools/gfx.py export [--res res] [--gfx gfx]     res/*.bin  -> gfx/*.png
    python tools/gfx.py import [--res res] [--gfx gfx] [--out res]
                                                           gfx/*.png  -> *.bin
    python tools/gfx.py list

Every PNG is a sheet of equal cells separated by 1-pixel blue lines (the lines
are ignored on import). Pixel colours:

    plain graphics    white = ink (1), black = paper (0)
    masked graphics   white = ink, black = solid paper, magenta = transparent
                      (pink = ink that is also marked transparent; rare)
    loading.png       the 15 Spectrum colours; max 2 per 8x8 cell

`import --out DIR` writes the changed binaries to another directory, so an
alternative graphics set can live beside the original:
    python tools/gfx.py export --gfx gfx_new          (then edit gfx_new/*.png)
    python tools/gfx.py import --gfx gfx_new --out res_new
    python build.py --res res_new
Bytes of a resource that no sheet covers (code, music, tables) are copied from
--res unchanged.
"""
import os, sys
from PIL import Image

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
GRID = (0, 0, 160)
WHITE, BLACK, MAGENTA, PINK = (255, 255, 255), (0, 0, 0), (255, 0, 255), (255, 176, 255)

# Sheet: (png name, resource, offset, width in bytes, rows, count, columns, mode, comment)
#   mode 'plain': rows of w bytes
#   mode 'pair' : rows of w (ink, mask) byte pairs; mask bit 1 = keep background
#   mode 'planes': per cell h rows of ink, then h rows of mask
def sprites(res, count, note):
    return (res, res + '.bin', 0, 5, 42, count, 13, 'plain', note)

def tiles(res):
    t = res + '.bin'
    return [
        (res + '_clip',     t, 0,    4, 56, 6, 6, 'plain', 'sprite clipping masks of the wall pieces (white = sprite hidden)'),
        (res + '_gate',     t, 1344, 3, 240, 1, 1, 'plain', 'portcullis bars (scrolled when the gate moves)'),
        (res + '_gateframe', t, 2064, 3, 72, 2, 2, 'plain', 'portcullis: frame, then its mask'),
        (res + '_wall',     t, 2496, 7, 72, 2, 2, 'pair', 'wall block, window'),
        (res + '_pillar',   t, 4512, 7, 72, 2, 2, 'pair', 'pillar, second piece'),
        (res + '_floor',    t, 6542, 7, 32, 5, 5, 'pair', 'floor pieces: FL2 (debris), FL, FL1 (loose), FL3, FL4 (buttons)'),
    ]

def longgate(res):
    t = res + '.bin'
    return [
        (res + '_long',  t, 0,    7, 38, 11, 11, 'plain', 'wide sprites 56x38: long jump, sword fight'),
        (res + '_exit',  t, 3000, 8, 66, 1, 1, 'plain', 'level exit: door frame'),
        (res + '_door',  t, 3528, 5, 57, 2, 2, 'plain', 'level exit: door leaf, stairs behind it'),
    ]

SHEETS = [
    sprites('prince', 78, 'prince, sprites 0..77 (40x42, the outline is generated by the game)'),
    sprites('prince1', 78, 'prince, sprites 78..155'),
    sprites('prince2', 40, 'guard, sprites 156.. (levels 1,2,4..11)'),
    sprites('prince2a', 40, 'enemy set A (level 3)'),
    sprites('prince2b', 40, 'enemy set B (level 12)'),
    sprites('prince2c', 40, 'enemy set C (level 13)'),
    ('high', 'high.bin', 15, 3, 55, 7, 7, 'plain', 'tall sprites 24x55 (hanging, climbing); the last one is cut by the file end'),
    ('steel', 'steelmir.bin', 0, 4, 54, 5, 5, 'planes', 'chopper blades, 5 frames'),
    ('mirror', 'steelmir.bin', 2160, 3, 56, 2, 2, 'plain', 'mirror, then its mask'),
    ('fire', 'fire.bin', 0, 1, 16, 9, 9, 'plain', 'torch flame, 9 frames'),
    ('font1', 'font1.bin', 0, 1, 8, 96, 16, 'plain', 'ending font, chars 32..127'),
] + tiles('tiles') + tiles('tilesa') + longgate('longgate') + longgate('longgata') + longgate('longgatb')
SCREENS = [('loading', 'loading.bin', 'loading screen (standard 6912-byte screen)')]

PAL = [(0, 0, 0), (0, 0, 205), (205, 0, 0), (205, 0, 205), (0, 205, 0), (0, 205, 205), (205, 205, 0), (205, 205, 205),
       (0, 0, 0), (0, 0, 255), (255, 0, 0), (255, 0, 255), (0, 255, 0), (0, 255, 255), (255, 255, 0), (255, 255, 255)]


def near(c, cols):
    return min(range(len(cols)), key=lambda i: sum((a - b) ** 2 for a, b in zip(c[:3], cols[i])))


def geometry(sh):
    name, res, off, w, h, n, cols, mode, note = sh
    rows = (n + cols - 1) // cols
    return (cols * (w * 8 + 1) + 1, rows * (h + 1) + 1)


def cell_origin(sh, i):
    name, res, off, w, h, n, cols, mode, note = sh
    return (i % cols) * (w * 8 + 1) + 1, (i // cols) * (h + 1) + 1


def addr(sh, i, y, x):
    """-> (ink offset, mask offset or None) of byte x in row y of cell i"""
    name, res, off, w, h, n, cols, mode, note = sh
    if mode == 'pair':
        p = off + (i * h + y) * w * 2 + x * 2
        return p, p + 1
    if mode == 'planes':
        p = off + i * h * w * 2 + y * w + x
        return p, p + h * w
    return off + (i * h + y) * w + x, None


def export_sheet(sh, data):
    name, res, off, w, h, n, cols, mode, note = sh
    step = w * (2 if mode == 'pair' else 1)
    img = Image.new('RGB', geometry(sh), GRID)
    px = img.load()
    for i in range(n):
        ox, oy = cell_origin(sh, i)
        for y in range(h):
            for x in range(w):
                p, q = addr(sh, i, y, x)
                if max(p, q or 0) >= len(data):
                    continue                                  # beyond the file: left as grid colour
                d = data[p]; m = data[q] if q is not None else 0
                for b in range(8):
                    bit = 0x80 >> b
                    if q is not None:
                        c = (PINK if m & bit else WHITE) if d & bit else (MAGENTA if m & bit else BLACK)
                    else:
                        c = WHITE if d & bit else BLACK
                    px[ox + x * 8 + b, oy + y] = c
    return img


def import_sheet(sh, img, data):
    name, res, off, w, h, n, cols, mode, note = sh
    if img.size != geometry(sh):
        raise SystemExit('%s.png: size is %dx%d, expected %dx%d (do not resize the sheet)' % ((name,) + img.size + geometry(sh)))
    px = img.convert('RGB').load()
    step = w * (2 if mode == 'pair' else 1)
    for i in range(n):
        ox, oy = cell_origin(sh, i)
        for y in range(h):
            for x in range(w):
                p, q = addr(sh, i, y, x)
                if max(p, q or 0) >= len(data):
                    continue
                d = m = 0
                for b in range(8):
                    c = px[ox + x * 8 + b, oy + y]
                    if q is not None:
                        k = near(c, (WHITE, BLACK, MAGENTA, PINK))
                        if k in (0, 3): d |= 0x80 >> b
                        if k in (2, 3): m |= 0x80 >> b
                    elif near(c, (WHITE, BLACK)) == 0:
                        d |= 0x80 >> b
                data[p] = d
                if q is not None:
                    data[q] = m


def export_scr(d):
    img = Image.new('RGB', (256, 192)); px = img.load()
    for y in range(192):
        row = ((y & 7) << 8) | (((y >> 3) & 7) << 5) | ((y >> 6) << 11)
        for xb in range(32):
            at = d[6144 + (y >> 3) * 32 + xb]; br = 8 if at & 64 else 0
            for b in range(8):
                px[xb * 8 + b, y] = PAL[br + ((at & 7) if d[row + xb] & (0x80 >> b) else (at >> 3) & 7)]
    return img


def import_scr(name, img, data):
    if img.size != (256, 192):
        raise SystemExit('%s.png: must be 256x192' % name)
    px = img.convert('RGB').load()
    for cy in range(24):
        for cx in range(32):
            idx = [[near(px[cx * 8 + x, cy * 8 + y], PAL) for x in range(8)] for y in range(8)]
            used = sorted({c & 7 for r in idx for c in r})
            if len(used) > 2:
                raise SystemExit('%s.png: more than 2 colours in cell column %d, row %d' % (name, cx, cy))
            bright = any(c >= 8 and (c & 7) for r in idx for c in r)
            paper = used[0]; ink = used[-1] if len(used) > 1 else (7 if paper == 0 else 0)
            if len(used) == 1 and paper != 0:
                ink, paper = paper, paper
            data[6144 + cy * 32 + cx] = (64 if bright else 0) | paper << 3 | ink
            for y in range(8):
                yy = cy * 8 + y
                row = ((yy & 7) << 8) | (((yy >> 3) & 7) << 5) | ((yy >> 6) << 11)
                v = 0
                for x in range(8):
                    if (idx[y][x] & 7) == ink and ink != paper: v |= 0x80 >> x
                data[row + cx] = v


def main(argv):
    def opt(name, default):
        return argv[argv.index(name) + 1] if name in argv else default
    cmd = argv[0] if argv else ''
    res = os.path.join(ROOT, opt('--res', 'res'))
    gfx = os.path.join(ROOT, opt('--gfx', 'gfx'))
    out = os.path.join(ROOT, opt('--out', opt('--res', 'res')))
    if cmd == 'list':
        for sh in SHEETS:
            print('%-18s %-13s +%-5d %2dx%-3d x%-3d %-5s %s' % (sh[0] + '.png', sh[1], sh[2], sh[3] * 8, sh[4], sh[5], sh[7], sh[8]))
        for name, r, note in SCREENS:
            print('%-18s %-13s %s' % (name + '.png', r, note))
    elif cmd == 'export':
        os.makedirs(gfx, exist_ok=True)
        for sh in SHEETS:
            export_sheet(sh, open(os.path.join(res, sh[1]), 'rb').read()).save(os.path.join(gfx, sh[0] + '.png'))
        for name, r, note in SCREENS:
            export_scr(open(os.path.join(res, r), 'rb').read()).save(os.path.join(gfx, name + '.png'))
        print('%d sheets -> %s' % (len(SHEETS) + len(SCREENS), gfx))
    elif cmd == 'import':
        files = {}
        def get(r):
            if r not in files:
                files[r] = bytearray(open(os.path.join(res, r), 'rb').read())
            return files[r]
        for sh in SHEETS:
            p = os.path.join(gfx, sh[0] + '.png')
            if os.path.exists(p): import_sheet(sh, Image.open(p), get(sh[1]))
        for name, r, note in SCREENS:
            p = os.path.join(gfx, name + '.png')
            if os.path.exists(p):
                d = bytearray(get(r)); import_scr(name, Image.open(p), d)
                if export_scr(d).tobytes() != export_scr(get(r)).tobytes():   # keep the bytes if the picture is the same
                    files[r] = d
        os.makedirs(out, exist_ok=True)
        changed = []
        for r, d in files.items():
            if bytes(d) != open(os.path.join(res, r), 'rb').read(): changed.append(r)
            if out != res or r in changed:
                open(os.path.join(out, r), 'wb').write(d)
        print('changed:', ', '.join(changed) if changed else 'nothing')
    else:
        print(__doc__)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
